@mcp.prompt()
def rag_qa_assistant(user_query: str) -> str:
    """Template for generating a grounded RAG answer."""
    return (
        f"You are a helpful AI assistant with access to thread-isolated documents.\n"
        f"Answer the user's question accurately using retrieved context.\n"
        f"User Query: {user_query}\n"
        f"Instructions:\n"
        f"1. Search relevant documents using `search_rag_context`.\n"
        f"2. Cite document filename and page numbers.\n"
        f"3. If context is missing, use web search fallback."
    )


@mcp.prompt()
def crag_fallback_policy() -> str:
    """Corrective RAG policy for autonomous web search fallback."""
    return (
        "CORRECTIVE RAG POLICY:\n"
        "1. For questions about uploaded PDFs, invoke `search_rag_context` first.\n"
        "2. If the document returns insufficient passages, immediately trigger web search.\n"
        "3. Explicitly inform the user when web search was used as a fallback because the document lacked the answer."
    )


@mcp.prompt()
def rag_triad_evaluation(question: str, context: str, answer: str) -> str:
    """Prompt template for RAG Triad evaluation."""
    return (
        f"Evaluate the following RAG turn on Faithfulness, Answer Relevance, and Context Precision:\n\n"
        f"Question: {question}\n"
        f"Retrieved Context: {context}\n"
        f"Generated Answer: {answer}\n\n"
        f"Provide numerical scores (1.0 - 5.0) and reasoning for each metric."
    )


