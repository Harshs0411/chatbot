@mcp.tool()
def chat_agent_turn(message: str, thread_id: str = "mcp-default") -> str:
    """
    Executes a conversational turn through the LangGraph ReAct agent.
    Maintains persistent memory in SQLite and applies Corrective RAG (CRAG).
    
    Args:
        message: The user's input prompt or question.
        thread_id: Target conversation thread ID for session isolation.
    """
    # Ensure thread exists
    db_create_thread(thread_id, title="MCP Session")

    config = {
        "configurable": {"thread_id": str(thread_id)},
        "metadata": {"thread_id": str(thread_id)},
    }
    result = workflow.invoke(
        {"messages": [HumanMessage(content=message)]},
        config=config,
    )
    messages = result.get("messages", [])
    if messages:
        last_msg = messages[-1]
        return getattr(last_msg, "content", str(last_msg))
    return "No response generated by agent."


@mcp.tool()
def search_rag_context(query: str, thread_id: str = "mcp-default", top_k: int = 4) -> Dict[str, Any]:
    """
    Performs thread-isolated vector retrieval directly against ChromaDB.
    Returns matched chunks, source filenames, and page numbers.
    
    Args:
        query: Search query or question.
        thread_id: Conversation thread ID to scope retrieval to.
        top_k: Number of relevant passages to return (default: 4).
    """
    with get_connection() as conn:
        cursor = conn.cursor()
        cursor.execute(
            "SELECT document_id FROM thread_documents WHERE thread_id = ?",
            (str(thread_id),)
        )
        thread_doc_ids = [row[0] for row in cursor.fetchall()]

    if not thread_doc_ids:
        return {
            "status": "no_documents",
            "message": f"No documents are indexed for thread_id '{thread_id}'.",
            "results": []
        }

    relevant_docs = vector_store.similarity_search(
        query,
        k=int(top_k),
        filter={"document_id": {"$in": thread_doc_ids}}
    )

    results = []
    for doc in relevant_docs:
        results.append({
            "content": doc.page_content,
            "filename": doc.metadata.get("filename", "unknown"),
            "page": doc.metadata.get("page", 1),
            "document_id": doc.metadata.get("document_id"),
        })

    return {
        "status": "success",
        "thread_id": thread_id,
        "query": query,
        "count": len(results),
        "passages": results
    }


@mcp.tool()
def ingest_pdf_document(file_path: str, thread_id: str = "mcp-default") -> Dict[str, Any]:
    """
    Ingests a local digital PDF into ChromaDB and maps it to a specific thread.
    Uses native digital text extraction with PyPDFLoader (fast, deterministic, no OCR overhead).
    
    Args:
        file_path: Absolute or relative path to the PDF file.
        thread_id: Thread ID to associate the document with.
    """
    if not os.path.isfile(file_path):
        return {"status": "error", "message": f"File not found: {file_path}"}

    with open(file_path, "rb") as f:
        pdf_bytes = f.read()

    filename = os.path.basename(file_path)
    summary = ingest_pdf(pdf_bytes, thread_id=thread_id, filename=filename)
    return {
        "status": "success",
        "summary": summary
    }


import ast
import operator as op

# Supported operators for safe arithmetic
SAFE_OPERATORS = {
    ast.Add: op.add,
    ast.Sub: op.sub,
    ast.Mult: op.mul,
    ast.Div: op.truediv,
    ast.Pow: op.pow,
    ast.USub: op.neg,
}

def safe_eval_expr(expr_str: str) -> float:
    """Safely evaluates a mathematical expression using AST parsing."""
    def eval_node(node):
        if isinstance(node, ast.Constant) and isinstance(node.value, (int, float)):
            return node.value
        elif isinstance(node, ast.BinOp):
            if type(node.op) not in SAFE_OPERATORS:
                raise ValueError(f"Operator {type(node.op).__name__} is not supported.")
            left = eval_node(node.left)
            right = eval_node(node.right)
            if isinstance(node.op, ast.Div) and right == 0:
                raise ZeroDivisionError("Division by zero is undefined.")
            return SAFE_OPERATORS[type(node.op)](left, right)
        elif isinstance(node, ast.UnaryOp):
            if type(node.op) not in SAFE_OPERATORS:
                raise ValueError(f"Unary operator {type(node.op).__name__} is not supported.")
            return SAFE_OPERATORS[type(node.op)](eval_node(node.operand))
        else:
            raise TypeError(f"Unsupported syntax: {type(node).__name__}")

    tree = ast.parse(expr_str, mode='eval').body
    return eval_node(tree)


@mcp.tool()
def calculate_expression(expression: str) -> Dict[str, Any]:
    """
    Safely calculates mathematical expressions without using eval().
    Supports addition, subtraction, multiplication, division, powers, and parentheses.
    
    Args:
        expression: Mathematical expression string, e.g. '(15 * 4) / 2 + 10'
    """
    try:
        res = safe_eval_expr(expression)
        return {
            "status": "success",
            "expression": expression,
            "result": round(float(res), 6)
        }
    except Exception as e:
        return {
            "status": "error",
            "expression": expression,
            "error": str(e)
        }


@mcp.tool()
def evaluate_rag(question: str, context: List[str], answer: str) -> Dict[str, Any]:
    """
    Evaluates a RAG response using the RAG Triad benchmark via LLM-as-a-judge:
    - Faithfulness (Groundedness) [1.0 - 5.0]
    - Answer Relevance [1.0 - 5.0]
    - Context Precision [1.0 - 5.0]
    
    Args:
        question: The original user question.
        context: List of retrieved context string chunks.
        answer: The generated answer to evaluate.
    """
    if run_evaluation is None:
        return {"status": "error", "message": "Evaluator module not available."}

    return run_evaluation(question=question, context=context, answer=answer)


@mcp.tool()
def list_conversation_threads() -> List[Dict[str, str]]:
    """
    Retrieves all persistent conversation threads stored in the SQLite database.
    """
    all_threads = db_get_all_threads()
    return [{"thread_id": t[0], "title": t[1]} for t in all_threads]


@mcp.tool()
def create_conversation_thread(title: str = "New Chat") -> Dict[str, str]:
    """
    Creates a new persistent conversation thread session.
    
    Args:
        title: Descriptive title for the conversation.
    """
    new_id = str(uuid.uuid4())
    db_create_thread(new_id, title=title)
    return {"thread_id": new_id, "title": title}


