def main():
    parser = argparse.ArgumentParser(description="Model Context Protocol (MCP) Server for LangGraph RAG Agent")
    parser.add_argument(
        "--transport",
        choices=["stdio", "sse"],
        default="stdio",
        help="Transport protocol (stdio for local clients like Claude Desktop/Cursor, sse for remote network clients)"
    )
    parser.add_argument(
        "--port",
        type=int,
        default=8000,
        help="Port for SSE transport (default: 8000)"
    )
    parser.add_argument(
        "--host",
        type=str,
        default="0.0.0.0",
        help="Host address for SSE transport (default: 0.0.0.0)"
    )

    args = parser.parse_args()

    if args.transport == "stdio":
        # Stdio mode for Claude Desktop, Cursor, Antigravity
        mcp.run(transport="stdio")
    else:
        # SSE mode for HTTP clients
        print(f"Starting MCP Server on http://{args.host}:{args.port} (transport=sse)...")
        mcp.run(transport="sse", host=args.host, port=args.port)


if __name__ == "__main__":
    main()
