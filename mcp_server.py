@mcp.resource("rag://threads")
def resource_all_threads() -> str:
    """Returns a JSON summary of all conversation threads."""
    threads = db_get_all_threads()
    data = [{"thread_id": t[0], "title": t[1]} for t in threads]
    return json.dumps(data, indent=2)


@mcp.resource("rag://threads/{thread_id}/documents")
def resource_thread_documents(thread_id: str) -> str:
    """Returns all documents indexed for a specific conversation thread."""
    docs = thread_document_metadata(thread_id)
    return json.dumps(docs, indent=2)


@mcp.resource("rag://threads/{thread_id}/history")
def resource_thread_history(thread_id: str) -> str:
    """Returns serialized message history for a thread from LangGraph checkpoint state."""
    try:
        state = workflow.get_state(config={"configurable": {"thread_id": thread_id}})
        raw_messages = state.values.get("messages", [])
        history = [
            {"role": getattr(m, "type", "message"), "content": getattr(m, "content", str(m))}
            for m in raw_messages
        ]
        return json.dumps(history, indent=2)
    except Exception as e:
        return json.dumps({"error": str(e)}, indent=2)


@mcp.resource("rag://system/status")
def resource_system_status() -> str:
    """Returns system status, active database paths, and indexing metrics."""
    with get_connection() as conn:
        cursor = conn.cursor()
        cursor.execute("SELECT COUNT(*) FROM threads")
        thread_count = cursor.fetchone()[0]
        cursor.execute("SELECT COUNT(*) FROM documents")
        doc_count = cursor.fetchone()[0]

    status = {
        "status": "healthy",
        "protocol": "Model Context Protocol (MCP)",
        "sqlite_db": os.path.exists(os.path.join(ROOT_DIR, "chatbot.db")),
        "chroma_dir": os.path.exists(os.path.join(ROOT_DIR, "chroma_db")),
        "total_threads": thread_count,
        "total_indexed_documents": doc_count,
    }
    return json.dumps(status, indent=2)


